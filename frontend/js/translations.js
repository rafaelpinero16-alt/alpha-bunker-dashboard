window.applyTranslations = function(lang) {
    const activeLang = lang || localStorage.getItem('alpha_lang') || 'es';
    const dict = translations[activeLang] || translations['es'];
    
    document.querySelectorAll('[data-i18n]').forEach(el => {
        const key = el.getAttribute('data-i18n');
        if (dict[key]) {
            if (el.tagName === 'INPUT' || el.tagName === 'TEXTAREA') {
                el.placeholder = dict[key];
            } else {
                el.innerText = dict[key];
            }
        }
    });

    const langBtnText = document.getElementById('fab-lang-text');
    if (langBtnText) {
        langBtnText.innerText = activeLang.toUpperCase();
    }
};